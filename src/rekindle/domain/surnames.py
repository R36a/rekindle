def surname_length(text: str, extra_surnames: Iterable[str] = ()) -> int:
    '''返回开头姓氏长度：有姓=1，没有=0。复姓不特殊处理。

    extra_surnames：从已有人脉学到的首字（如「公」），用来识别生僻姓。
    '''
    if not text:
        return 0
    first = text[0]
    if first in BIG_SURNAMES or first in SMALL_SURNAMES:
        return 1
    if first in extra_surnames:
        return 1
    return 0
